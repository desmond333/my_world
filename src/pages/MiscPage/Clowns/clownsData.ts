export type ClownMeterResult = {
  percent: number
  verdict: string
  label: string
}

export const getClownMeterVerdict = (percent: number): ClownMeterResult => {
  if (percent <= 25) {
    return { percent, label: 'Уровень: Кремень', verdict: 'Чисто Стэйтем в строгом костюме. Ни тени улыбки.' }
  }
  if (percent <= 50) {
    return { percent, label: 'Уровень: Лёгкий хонк', verdict: 'Улыбнулся одним уголком рта, но держишь пацанскую стойку.' }
  }
  if (percent <= 75) {
    return { percent, label: 'Уровень: Опасная зона', verdict: 'Уже вовсю жонглируешь горящими задачами под музыку цирка.' }
  }
  if (percent <= 95) {
    return { percent, label: 'Уровень: Фулл цирк', verdict: 'Красный поролоновый нос прирос к лицу. Остановиться невозможно.' }
  }
  return { percent, label: 'Уровень: 100% АУФ', verdict: 'Главный шпрехшталмейстер вселенной. Манеж аплодирует стоя!' }
}
